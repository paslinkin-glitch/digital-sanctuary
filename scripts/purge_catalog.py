#!/usr/bin/env python3
"""Final atmospheric purge for Digital Sanctuary.

Removes the remaining food/office/gym/toy clips, syncs archetype to stage,
renames labels in neutral Russian, and keeps each stage in the 15–22 range
using only already-validated 1080p+ atmospheric coverr clips.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VIDEOS = ROOT / "videos.json"
BACKUP = ROOT / "videos.backup.json"
DATA = ROOT / "videos-data.js"

BAD = [
    "donuts", "berries", "blueberries", "strawberries", "ice cream",
    "champagne", "toast", "macbook", "keyboard", "computer", "notepad",
    "gym", "muscular", "battle ropes", "nft", "smartphone", "laptop",
    "carousel", "soccer", "oil rig", "statue of liberty", "pinwheel",
    "snail", "trash", "newsstand", "bubbles", "fashion", "makeup",
    "sunglasses", "trombone", "dancer", "spiral background",
]
BAD_RE = re.compile("|".join(re.escape(word) for word in BAD), re.I)
ARCH = {
    "shadow": "Тень",
    "trickster_abyss": "Трикстер и Бездна",
    "calm": "Покой / Анима",
    "path": "Путь / Самость",
}
RU = {"shadow": "Тень", "trickster_abyss": "Трикстер", "calm": "Покой", "path": "Путь"}


def good(item: dict) -> bool:
    return (
        float(item.get("size") or 0) >= 4_500_000
        and int(item.get("width") or 0) >= 1080
        and int(item.get("height") or 0) >= 1920
        and float(item.get("size") or 0) * 8 / max(1.0, float(item.get("duration") or 0)) >= 2_500_000
    )


def text(item: dict) -> str:
    return f"{item.get('title', '')} {item.get('description', '')}"


def main() -> int:
    current = json.loads(VIDEOS.read_text(encoding="utf-8"))
    backup = json.loads(BACKUP.read_text(encoding="utf-8"))
    clean = [item for item in current if not BAD_RE.search(text(item))]
    print("removed", len(current) - len(clean), "from current")

    used_ids = {item["id"] for item in clean}
    used_urls = {item["url"] for item in clean}
    used_titles = {item["title"] for item in clean}

    # Fill shadow/trickster only with atmospheric, high-bitrate, non-stopword
    # records that already passed the previous quality gate in the backup.
    for stage, needed in (("shadow", 3), ("trickster_abyss", 2)):
        added = 0
        for item in sorted(backup, key=lambda x: -(x.get("size") or 0)):
            if added >= needed:
                break
            if item.get("stage") != stage or not good(item) or BAD_RE.search(text(item)):
                continue
            if item.get("id") in used_ids or item.get("url") in used_urls or item.get("title") in used_titles:
                continue
            clean.append(dict(item))
            used_ids.add(item["id"])
            used_urls.add(item["url"])
            used_titles.add(item["title"])
            added += 1

    # Bring two water/storm frames into the Abyss stage instead of adding junk.
    reclass = {
        "Ocean water surface at sunset. Sea wave splashing with sunset in the background. Vertical Video": "trickster_abyss",
        "Strong waves and splashes crashing and splashing on the rocks on a sunny day and rough sea. Mighty sea waves breaking over rocks on beach Megas Limnionas, Chios, Greece": "trickster_abyss",
    }
    for item in clean:
        target = reclass.get(item["title"])
        if target:
            item["stage"] = target

    counts = Counter(item["stage"] for item in clean)
    print("pre-sync", dict(counts), "total", len(clean))

    for stage in ARCH:
        n = 1
        for item in clean:
            if item.get("stage") != stage:
                continue
            item["archetype"] = ARCH[stage]
            item["title_ru"] = f"{RU[stage]} {n:02d}"
            n += 1

    # Keep a 15-frame dawn/quiet finale pool in path.
    path = [item for item in clean if item.get("stage") == "path"]
    finals = [item for item in path if item.get("is_finale")]
    for item in path:
        if len(finals) >= 15:
            break
        if not item.get("is_finale"):
            item["is_finale"] = True
            finals.append(item)
    for item in clean:
        if item.get("stage") != "path":
            item["is_finale"] = False

    counts = Counter(item["stage"] for item in clean)
    if any(counts[stage] < 15 for stage in ARCH):
        print("stage below 15:", dict(counts))
        return 2

    VIDEOS.write_text(json.dumps(clean, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    DATA.write_text(
        "/* Generated by scripts/purge_catalog.py. */\n"
        "window.VIDEOS_DATA = " + json.dumps(clean, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print("FINAL", len(clean), dict(counts), "finals", sum(1 for x in clean if x.get("is_finale")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
