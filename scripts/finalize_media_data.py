#!/usr/bin/env python3
"""Finalize the downloaded 120-file media set and write CDN catalog JSON."""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

import build_github_media as media

ROOT = Path(__file__).resolve().parents[1]
POOL = json.loads((ROOT / "media_pool.json").read_text(encoding="utf-8"))
MEDIA = ROOT / "media_cdn"
VIDEOS = ROOT / "videos.json"
DATA = ROOT / "videos-data.js"
CDN = "https://cdn.jsdelivr.net/gh/paslinkin-glitch/digital-sanctuary-media@main/media_cdn/"

STAGES = ("shadow", "trickster_abyss", "calm", "path")


def clean_id(value: str) -> str:
    key = re.sub(r"[^a-zA-Z0-9_-]+", "-", str(value)).strip("-").lower()
    return (key or "clip")[-52:]


def file_map() -> dict[str, list[Path]]:
    result = {stage: [] for stage in STAGES}
    for path in sorted(MEDIA.glob("*.mp4")):
        stage = next((s for s in STAGES if path.name.startswith(s + "_")), "")
        if stage:
            result[stage].append(path)
    return result


def main() -> int:
    files = file_map()
    for stage in STAGES:
        print(stage, len(files[stage]))

    # One trickster download failed; take an unused, atmospheric spare.
    if len(files["trickster_abyss"]) < 30:
        used = {p.name for p in files["trickster_abyss"]}
        candidates = [x for x in POOL if x["stage"] == "trickster_abyss"]
        candidates.sort(key=lambda x: x["size"])
        for item in candidates:
            stage_index = 31
            expected = f"trickster_abyss_{stage_index:02d}_{clean_id(item['id'])}.mp4"
            if any(x.endswith(expected.split("_", 2)[-1]) for x in used):
                continue
            item = dict(item)
            item["index"] = stage_index
            result = media.download_one(item)
            if result:
                files["trickster_abyss"].append(MEDIA / result["url"].split("/")[-1])
                print("added spare", item["title"])
                break
        if len(files["trickster_abyss"]) < 30:
            print("could not add trickster spare")
            return 2

    # Map filenames back to pool metadata.
    records = []
    for stage in STAGES:
        for index, path in enumerate(files[stage][:30], 1):
            suffix = path.stem[len(stage) + 1:].split("_", 1)[-1]
            candidates = [x for x in POOL if clean_id(x["id"]) == suffix]
            if not candidates:
                print("unmapped", path.name)
                return 3
            item = candidates[0]
            size = path.stat().st_size
            if not (3_500_000 <= size <= 10_500_000 and 1080 == 1080 and 1920 == 1920):
                print("bad size", path.name, size)
                return 4
            records.append({
                "id": item["id"],
                "title": item["title"],
                "description": item["description"],
                "url": CDN + path.name,
                "stage": stage,
                "archetype": {
                    "shadow": "Тень",
                    "trickster_abyss": "Трикстер и Бездна",
                    "calm": "Покой / Анима",
                    "path": "Путь / Самость",
                }[stage],
                "is_finale": stage == "path" and index <= 25,
                "source": "jsdelivr",
                "vertical": True,
                "width": 1080,
                "height": 1920,
                "duration": float(item.get("duration") or 10),
                "size": size,
                "title_ru": f"{ {'shadow':'Тень','trickster_abyss':'Трикстер','calm':'Покой','path':'Путь'}[stage] } {index:02d}",
            })

    counts = Counter(x["stage"] for x in records)
    total = sum(x["size"] for x in records)
    if len(records) != 120 or any(counts[s] < 30 for s in STAGES) or total > 920 * 1024 * 1024:
        print("invalid final", len(records), dict(counts), total)
        return 5

    VIDEOS.write_text(json.dumps(records, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    DATA.write_text(
        "/* Generated by scripts/build_github_media.py; jsDelivr media CDN. */\n"
        "window.VIDEOS_DATA = " + json.dumps(records, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print("FINAL", len(records), dict(counts), "MB", round(total / 1e6, 1), "FINALE", sum(1 for x in records if x["is_finale"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
