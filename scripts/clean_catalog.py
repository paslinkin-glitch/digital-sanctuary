#!/usr/bin/env python3
"""Crystal-clear catalog pass for Digital Sanctuary.

Keeps only 1080p+ 9:16 videos with >=4.5 MB and >=2.5 Mbps, removes duplicate
ids/urls/titles, balances four 25-video stages, and writes neutral Russian
title_ru labels. The previous 160-item catalog remains in videos.backup.json.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VIDEOS = ROOT / "videos.json"
DATA = ROOT / "videos-data.js"

MIN_SIZE = 4_500_000
MIN_WIDTH = 1080
MIN_HEIGHT = 1920
MIN_BITRATE = 2_500_000
MAX_SIZE = 12_500_000
TARGET_PER_STAGE = 25

RU_STAGE = {
    "shadow": "Тень",
    "trickster_abyss": "Трикстер",
    "calm": "Покой",
    "path": "Путь",
}

PATH_HINTS = re.compile(r"\b(road|walk|beach|shore|sunrise|dawn|horizon|train|mountain|path|journey|flight|bird|view)\b", re.I)
CALM_HINTS = re.compile(r"\b(lake|forest|rain|cloud|sun|leaf|leaves|mist|river|water|flower|snow|calm)\b", re.I)


def bitrate(item: dict) -> float:
    duration = max(1.0, float(item.get("duration") or 0))
    return float(item.get("size") or 0) * 8 / duration


def is_crystal(item: dict) -> bool:
    width = int(item.get("width") or 0)
    height = int(item.get("height") or 0)
    size = int(item.get("size") or 0)
    if width != 1080 or height != 1920 or size < MIN_SIZE or size > MAX_SIZE:
        return False
    if abs(width / height - 9 / 16) > 0.02:
        return False
    return bitrate(item) >= MIN_BITRATE


def main() -> int:
    old = json.loads(VIDEOS.read_text(encoding="utf-8"))
    seen_ids = set()
    seen_urls = set()
    seen_titles = set()
    clean = []
    for item in old:
        if not is_crystal(item):
            continue
        ident = str(item.get("id") or "")
        url = str(item.get("url") or "")
        title = re.sub(r"[^a-zа-яё0-9]+", " ", str(item.get("title") or "").lower()).strip()
        if not ident or not url or not title:
            continue
        if ident in seen_ids or url in seen_urls:
            continue
        seen_ids.add(ident)
        seen_urls.add(url)
        clean.append(dict(item))

    clean.sort(key=lambda item: -bitrate(item))

    # Rebalance without lowering the quality bar. These are symbolic
    # reclassifications, not lower-quality substitutes.
    def take(stage: str, predicate, count: int) -> list[dict]:
        picks = []
        for item in list(clean):
            if item.get("stage") != stage or len(picks) >= count:
                continue
            if predicate(item.get("title", "")):
                picks.append(item)
                clean.remove(item)
        return picks

    calm_pool = [item for item in clean if item.get("stage") == "shadow" and CALM_HINTS.search(item.get("title", ""))]
    calm_pool.sort(key=lambda item: -bitrate(item))
    for item in calm_pool[:7]:
        item["stage"] = "calm"

    extra_calm = [item for item in clean if item.get("stage") == "trickster_abyss" and CALM_HINTS.search(item.get("title", ""))]
    extra_calm.sort(key=lambda item: -bitrate(item))
    for item in extra_calm[:2]:
        item["stage"] = "calm"

    path_pool = [item for item in clean if item.get("stage") == "trickster_abyss" and PATH_HINTS.search(item.get("title", ""))]
    path_pool.sort(key=lambda item: -bitrate(item))
    for item in path_pool[:9]:
        item["stage"] = "path"

    selected = []
    for stage in ("shadow", "trickster_abyss", "calm", "path"):
        rows = [item for item in clean if item.get("stage") == stage]
        rows.sort(key=lambda item: -bitrate(item))
        selected.extend(rows[:TARGET_PER_STAGE])

    # The path finale pool must stay at 15+ quiet dawn/horizon frames.
    path_rows = [item for item in selected if item.get("stage") == "path"]
    finals = [item for item in path_rows if item.get("is_finale")]
    for item in path_rows:
        if len(finals) >= 15:
            break
        if not item.get("is_finale"):
            item["is_finale"] = True
            finals.append(item)
    for item in selected:
        if item.get("stage") != "path":
            item["is_finale"] = False

    for stage in ("shadow", "trickster_abyss", "calm", "path"):
        n = 1
        for item in selected:
            if item.get("stage") != stage:
                continue
            item["title_ru"] = f"{RU_STAGE[stage]} {n:02d}"
            n += 1

    unique = selected

    counts = Counter(item["stage"] for item in unique)
    if any(counts[stage] < 25 for stage in ("shadow", "trickster_abyss", "calm", "path")):
        print("not enough quality items:", counts)
        return 2

    VIDEOS.write_text(json.dumps(unique, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    DATA.write_text(
        "/* Generated by scripts/clean_catalog.py. */\n"
        "window.VIDEOS_DATA = " + json.dumps(unique, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )

    sizes = [item["size"] for item in unique]
    print("KEYS", len(unique), dict(counts), "finals", sum(1 for x in unique if x.get("is_finale")))
    print("size min", min(sizes), "avg", round(sum(sizes) / len(sizes)), "max", max(sizes))
    print("sources", dict(Counter(item["source"] for item in unique)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
